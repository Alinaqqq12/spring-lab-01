-- Lab 10 preparation: catalogue schema from Lab 8

CREATE TABLE IF NOT EXISTS author (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    country VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS publisher (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    country VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS book (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    author_name VARCHAR(255),
    publication_year INTEGER NOT NULL,
    genre VARCHAR(20) NOT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    author_id BIGINT REFERENCES author(id),
    publisher_id BIGINT REFERENCES publisher(id)
);

CREATE TABLE IF NOT EXISTS book_tag (
    book_id BIGINT NOT NULL REFERENCES book(id),
    tag_id BIGINT NOT NULL REFERENCES tag(id),
    PRIMARY KEY (book_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_book_author_id
    ON book(author_id);

CREATE INDEX IF NOT EXISTS idx_book_publisher_id
    ON book(publisher_id);